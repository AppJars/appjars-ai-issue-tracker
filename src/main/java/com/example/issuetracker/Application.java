package com.example.issuetracker;

import com.appjars.AppJarsAutoConfiguration;
import com.appjars.activitylog.ActivityLogAutoConfiguration;
import com.appjars.issuetracker.IssueTrackerAutoConfiguration;
import com.appjars.usermanager.UserManagerAutoConfiguration;
import com.vaadin.flow.component.dependency.NpmPackage;
import com.vaadin.flow.component.dependency.StyleSheet;
import com.vaadin.flow.component.page.AppShellConfigurator;
import com.vaadin.flow.component.page.Push;
import com.vaadin.flow.spring.annotation.EnableVaadin;
import com.vaadin.flow.theme.lumo.Lumo;
import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.context.annotation.ComponentScan;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;

/**
 * Entry point of Issue Tracker.
 *
 * <p>Everything that makes the AppJars modules visible to Spring and Vaadin is declared on this
 * class. Every annotation below carries a comment saying why it is there; several look redundant
 * and fail silently when removed.
 *
 * <p>Generated by Craft (https://craft.appjars.com).
 */
@SpringBootApplication
// Packages Vaadin scans for routes, layouts and the AppShellConfigurator (this class). The
// application's own package MUST stay in the list: if the package of the AppShellConfigurator is
// missing, Vaadin 25 silently falls back to the Aura theme and ignores every @StyleSheet below.
@EnableVaadin({
    "com.appjars.activitylog.flow",
    "com.appjars.issuetracker.flow",
    "com.appjars.usermanager.flow",
    "com.example.issuetracker"
})
// Declaring @ComponentScan replaces the default package scan of @SpringBootApplication, so
// Application.class must be listed or the application's own beans are never registered.
// AppJarsAutoConfiguration is the infrastructure shared by all AppJars (i18n provider, common
// components); it is not registered through auto-configuration imports and has to be scanned.
// Each *AutoConfiguration registers that module's beans and JPA entities.
@ComponentScan(basePackageClasses = {
    AppJarsAutoConfiguration.class,
    ActivityLogAutoConfiguration.class,
    IssueTrackerAutoConfiguration.class,
    UserManagerAutoConfiguration.class,
    Application.class
})
// Spring Data repositories of these modules live outside this application's package, so Spring
// Boot's default repository scan would never find them.
@EnableJpaRepositories(basePackageClasses = {
    ActivityLogAutoConfiguration.class,
    IssueTrackerAutoConfiguration.class
})
// Server push: some modules stream updates into their views (live logs, process status, chat).
@Push
// Frontend add-ons of the integrated modules import this package without declaring it.
@NpmPackage(value = "@polymer/polymer", version = "3.5.2")
// Vaadin 25 themes are plain stylesheets: @Theme and theme.json are legacy and silently ignored.
@StyleSheet(Lumo.STYLESHEET)
@StyleSheet(Lumo.UTILITY_STYLESHEET)
// The application's own styles: src/main/resources/META-INF/resources/styles.css
@StyleSheet("styles.css")
public class Application implements AppShellConfigurator {

    public static void main(String[] args) {
        SpringApplication.run(Application.class, args);
    }
}
